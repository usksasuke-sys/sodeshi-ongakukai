function paras(lines) {
  return lines.map(function (line) {
    return "<p>" + line + "</p>";
  }).join("");
}

function talk(source, title, sub, rows) {
  var html = "<p class=\"source\">" + source + "</p><div class=\"phone\"><div class=\"bar\"><div class=\"who-title\">" + title + "</div>";
  if (sub) html += "<div class=\"sub\">" + sub + "</div>";
  html += "</div><div class=\"log\">";
  rows.forEach(function (row) {
    if (row.kind === "day") {
      html += "<div class=\"day\"><span>" + row.text + "</span></div>";
    } else if (row.kind === "call") {
      html += "<div class=\"call\">" + row.text + "</div>";
    } else {
      html += "<div class=\"bubble" + (row.me ? " me" : "") + "\">";
      if (!row.me && row.name) html += "<div class=\"name\">" + row.name + "</div>";
      html += "<div class=\"body\">" + row.text + "</div>";
      var meta = row.time || "";
      if (row.me && row.read) meta = (meta ? meta + " 既読" : "既読");
      if (meta) html += "<div class=\"meta\">" + meta + "</div>";
      html += "</div>";
    }
  });
  return html + "</div></div>";
}

